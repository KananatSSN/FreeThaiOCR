import { Audio } from '@remotion/media';
import { linearTiming, TransitionSeries } from '@remotion/transitions';
import { fade } from '@remotion/transitions/fade';
import { slide } from '@remotion/transitions/slide';
import { wipe } from '@remotion/transitions/wipe';
import type React from 'react';
import { Easing, interpolate, staticFile, useVideoConfig } from 'remotion';
import { BatchScene } from './scenes/BatchScene';
import { BoxScene } from './scenes/BoxScene';
import { CtaScene } from './scenes/CtaScene';
import { DetectScene } from './scenes/DetectScene';
import { ExportScene } from './scenes/ExportScene';
import { HookScene } from './scenes/HookScene';
import { PrivacyScene } from './scenes/PrivacyScene';
import { ResultsScene } from './scenes/ResultsScene';
import { UploadScene } from './scenes/UploadScene';

export type PromoProps = {
  /** Music track in public/ (generated by scripts/make-music.mjs). Empty = none. */
  readonly musicSrc: string;
  /** Whooshes on the cuts and the CTA hit, aligned to the same beats. Empty = none. */
  readonly sfxSrc: string;
  readonly musicVolume: number;
  readonly sfxVolume: number;
};

// Cut on the beat: the soundtrack is 120 BPM, so one beat = 15 frames. Each
// 8-frame transition is centred on a beat (frames 60, 120, 195, 255, 315, 390,
// 450, 510 = beats 4, 8, 13, 17, 21, 26, 30, 34). Scene lengths sum to 664
// frames; the 8 transitions overlap 64 of them, for a 600-frame (20 s) video.
const CUT = linearTiming({ durationInFrames: 8, easing: Easing.inOut(Easing.cubic) });

export const Promo: React.FC<PromoProps> = ({ musicSrc, sfxSrc, musicVolume, sfxVolume }) => {
  const { fps, durationInFrames } = useVideoConfig();
  return (
    <>
      <TransitionSeries>
        <TransitionSeries.Sequence name="Hook" durationInFrames={64} premountFor={fps}>
          <HookScene tag="OCR ภาษาไทย · ฟรี" line1="เปลี่ยน|*รูปภาพ*" line2="เป็น|*ข้อความ*" />
        </TransitionSeries.Sequence>
        <TransitionSeries.Transition presentation={slide({ direction: 'from-bottom' })} timing={CUT} />
        <TransitionSeries.Sequence name="Upload" durationInFrames={68} premountFor={fps}>
          <UploadScene title="ลากไฟล์ หรือ|*ทั้งโฟลเดอร์*" />
        </TransitionSeries.Sequence>
        <TransitionSeries.Transition presentation={wipe({ direction: 'from-right' })} timing={CUT} />
        <TransitionSeries.Sequence name="Detect" durationInFrames={83} premountFor={fps}>
          <DetectScene title="เจอทุก|*บรรทัด*|อัตโนมัติ" />
        </TransitionSeries.Sequence>
        <TransitionSeries.Transition presentation={slide({ direction: 'from-bottom' })} timing={CUT} />
        <TransitionSeries.Sequence name="Results" durationInFrames={68} premountFor={fps}>
          <ResultsScene title="ได้|*ข้อความ*|ทันที" subtitle="คัดลอก · แก้ไข · ส่งออก" />
        </TransitionSeries.Sequence>
        <TransitionSeries.Transition presentation={slide({ direction: 'from-right' })} timing={CUT} />
        <TransitionSeries.Sequence name="Box" durationInFrames={68} premountFor={fps}>
          <BoxScene title="ลาก|*กรอบ*|อ่านเฉพาะส่วน" />
        </TransitionSeries.Sequence>
        <TransitionSeries.Transition presentation={wipe({ direction: 'from-bottom' })} timing={CUT} />
        <TransitionSeries.Sequence name="Batch" durationInFrames={83} premountFor={fps}>
          <BatchScene title="ทั้ง|*โฟลเดอร์*|ในคลิกเดียว" />
        </TransitionSeries.Sequence>
        <TransitionSeries.Transition presentation={slide({ direction: 'from-right' })} timing={CUT} />
        <TransitionSeries.Sequence name="Export" durationInFrames={68} premountFor={fps}>
          <ExportScene title="ส่งออก|*ทุกแบบ*" />
        </TransitionSeries.Sequence>
        <TransitionSeries.Transition presentation={wipe({ direction: 'from-left' })} timing={CUT} />
        <TransitionSeries.Sequence name="Privacy" durationInFrames={68} premountFor={fps}>
          <PrivacyScene title="ไฟล์|*ไม่ออก*|จากเครื่อง" subtitle="OCR ทำงานในเบราว์เซอร์ ไม่มีการอัปโหลด" />
        </TransitionSeries.Sequence>
        <TransitionSeries.Transition presentation={fade()} timing={CUT} />
        <TransitionSeries.Sequence name="CTA" durationInFrames={94} premountFor={fps}>
          <CtaScene brand="Free|Thai|*OCR*" tagline="OCR ภาษาไทย ฟรี ในเบราว์เซอร์" url="github.com/KananatSSN/FreeThaiOCR" />
        </TransitionSeries.Sequence>
      </TransitionSeries>
      {musicSrc ? (
        <Audio
          name="Music"
          src={staticFile(musicSrc)}
          premountFor={fps}
          volume={(f) => interpolate(f, [durationInFrames - 12, durationInFrames], [musicVolume, 0], { extrapolateLeft: 'clamp', extrapolateRight: 'clamp' })}
        />
      ) : null}
      {sfxSrc ? <Audio name="SFX" src={staticFile(sfxSrc)} premountFor={fps} volume={sfxVolume} /> : null}
    </>
  );
};
